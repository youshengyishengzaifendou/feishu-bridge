'use strict';

/**
 * 即时回执 —— 收到消息后先回一句，再去干活。
 *
 * 为什么单独做一层：
 *   一条消息的完整处理要调 LLM（2~20 秒）、可能还要读表。
 *   老板发完消息后如果什么都没有，会以为没收到、或者以为卡死了。
 *   所以收到就先回执，让他知道「已经收到，正在处理」。
 *
 * 为什么不用 LLM 生成回执：
 *   「立刻」是唯一要求。这里只用本地关键词判断，零网络、零延迟，
 *   保证回执在处理开始之前就发出去。
 */

const RULES = [
  { re: /提醒我|记得提醒|别忘了|到点提醒|帮我提醒|定时提醒/, text: '收到，正在建提醒…' },
  { re: /删除|取消|不要了|去掉|删掉|合并/, text: '收到，正在处理…' },
  { re: /库龄|超龄|180\s*天/, text: '收到，我去查库龄表…' },
  // 「有货吗」「断货了吗」这类问法很常见，不能落到兜底的「收到…」
  { re: /库存|断货|无库存|剩多少|还有多少货|有货|缺货|售罄/, text: '收到，我去看库存…' },
  { re: /毛利|利润率|赔钱|亏|周报|销量|销售额|成本/, text: '收到，我去查周报…' },
  { re: /广告|竞价|投放|ACOS|CPC|活动|曝光|点击/, text: '收到，我去看广告记录…' },
  { re: /排名|review|评价|星级|差评/, text: '收到，我去看日运营表…' },
  { re: /产品|ASIN|SKU|哪几个|编码/, text: '收到，我查一下产品档案…' },
];

/**
 * 生成回执文本。
 * @param {string} text 老板的原话
 * @returns {string}
 */
function build(text) {
  const t = String(text || '').trim();
  if (!t) return '收到…';

  for (const r of RULES) {
    if (r.re.test(t)) return r.text;
  }

  // 有问号 / 疑问词 → 大概是问问题
  if (/[？?]|什么|怎么|多少|哪|如何|为什么|是不是/.test(t)) return '收到，我看一下…';

  return '收到…';
}

module.exports = { build };
